# Shared by scripts/build.sh and scripts/run.sh (sourced, not executed).
#
# Two installable apps, side by side on one phone:
#   prd -> « SOE »      cm.soe.mobile       https://api.solutionofeducation.com
#   stg -> « SOE Test » cm.soe.mobile.test  https://api.jeteste.site
# Values come from the Doppler project `soe-mobile` (configs dev, stg, prd).

DOPPLER_PROJECT="soe-mobile"

# Sets APP_ID, APP_NAME, ANDROID_ICON, IOS_ICON for the Doppler config $1 (stg or prd; dev uses
# the test identity, so that a development build never replaces the production app).
set_identity() {
  case "$1" in
    prd)
      APP_ID="cm.soe.mobile"
      APP_NAME="SOE"
      ANDROID_ICON="ic_launcher"
      IOS_ICON="AppIcon"
      ;;
    stg | dev)
      APP_ID="cm.soe.mobile.test"
      APP_NAME="SOE Test"
      ANDROID_ICON="ic_launcher_test"
      IOS_ICON="AppIconTest"
      ;;
    *)
      echo "Error: unknown config '$1' (expected dev, stg or prd)." >&2
      return 1
      ;;
  esac
}

# Writes the gitignored identity files read by Gradle and Xcode (android/env.properties and
# ios/Flutter/Env.xcconfig). Without them, both platforms build the production app.
write_identity_files() {
  cat > android/env.properties <<EOF
# Generated by scripts/build.sh / scripts/run.sh. Do not edit, do not commit.
APP_ID=$APP_ID
APP_NAME=$APP_NAME
APP_ICON=$ANDROID_ICON
EOF
  cat > ios/Flutter/Env.xcconfig <<EOF
// Generated by scripts/build.sh / scripts/run.sh. Do not edit, do not commit.
APP_BUNDLE_ID = $APP_ID
APP_DISPLAY_NAME = $APP_NAME
APP_ICON_NAME = $IOS_ICON
EOF
}

# Prints the value of Doppler secret $1 in config $2 (empty when the secret does not exist).
doppler_secret() {
  doppler secrets get "$1" --plain -p "$DOPPLER_PROJECT" -c "$2" 2>/dev/null || true
}

# Reads the app secrets of config $1 into API_BASE_URL, ONESIGNAL_APP_ID, SENTRY_DSN and
# GOOGLE_PLACES_API_KEY. The API URL is mandatory; the others may be empty (warning only).
load_app_secrets() {
  local config="$1"
  command -v doppler >/dev/null || { echo "Error: the Doppler CLI is required." >&2; return 1; }
  API_BASE_URL=$(doppler_secret API_BASE_URL "$config")
  ONESIGNAL_APP_ID=$(doppler_secret ONESIGNAL_APP_ID "$config")
  SENTRY_DSN=$(doppler_secret SENTRY_DSN "$config")
  GOOGLE_PLACES_API_KEY=$(doppler_secret GOOGLE_PLACES_API_KEY "$config")

  if [ -z "$API_BASE_URL" ]; then
    echo "Error: API_BASE_URL is empty in Doppler $DOPPLER_PROJECT/$config." >&2
    echo "  Check: doppler secrets -p $DOPPLER_PROJECT -c $config (if the project is not found," >&2
    echo "  this folder uses another Doppler workplace: run 'doppler setup -p $DOPPLER_PROJECT -c $config')." >&2
    return 1
  fi
  local name
  for name in ONESIGNAL_APP_ID SENTRY_DSN GOOGLE_PLACES_API_KEY; do
    if [ -z "${!name}" ]; then
      echo "Warning: $name is empty in Doppler $DOPPLER_PROJECT/$config (built without it)." >&2
    fi
  done
}

# The --dart-define flags for flavor $1, from the variables set by load_app_secrets.
dart_defines() {
  DART_DEFINES=(
    "--dart-define=FLAVOR=$1"
    "--dart-define=API_BASE_URL=$API_BASE_URL"
    "--dart-define=ONESIGNAL_APP_ID=$ONESIGNAL_APP_ID"
    "--dart-define=SENTRY_DSN=$SENTRY_DSN"
    "--dart-define=GOOGLE_PLACES_API_KEY=$GOOGLE_PLACES_API_KEY"
  )
}

# Recreates keys/upload-keystore.jks and android/key.properties from Doppler config $1 when one
# of them is missing (the Play upload key; same key in stg and prd). Never prints a secret.
restore_upload_key() {
  local config="$1"
  if [ -f keys/upload-keystore.jks ] && [ -f android/key.properties ]; then
    return 0
  fi
  echo "Restoring the Android upload key from Doppler $DOPPLER_PROJECT/$config..."
  local keystore store_password key_password key_alias
  keystore=$(doppler_secret ANDROID_KEYSTORE_BASE64 "$config")
  store_password=$(doppler_secret ANDROID_KEYSTORE_PASSWORD "$config")
  key_password=$(doppler_secret ANDROID_KEY_PASSWORD "$config")
  key_alias=$(doppler_secret ANDROID_KEY_ALIAS "$config")
  if [ -z "$keystore" ] || [ -z "$store_password" ] || [ -z "$key_password" ] || [ -z "$key_alias" ]; then
    echo "Warning: Android signing secrets missing in Doppler: release signed with the DEBUG key (Play refuses it)." >&2
    return 0
  fi
  (
    umask 077
    mkdir -p keys
    printf '%s' "$keystore" | base64 -d > keys/upload-keystore.jks
    cat > android/key.properties <<EOF
storePassword=$store_password
keyPassword=$key_password
keyAlias=$key_alias
storeFile=../keys/upload-keystore.jks
EOF
  )
}
